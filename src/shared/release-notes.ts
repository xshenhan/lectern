// Shown by "更新说明" next to the version in the sidebar. When the version in
// package.json changes, add an entry at the top with everything since the previous
// version: one sentence per item, new features and bug fixes listed separately.
// tests/release-notes.test.ts fails if the current version has no entry.
// Changes for the next release may be listed in one entry above the current
// version before package.json is bumped; the dialog marks it as pending.
//
// Each item is a `['中文', 'English']` pair, shown in the app's language. A
// plain Chinese string is allowed in the pending entry until it is translated;
// English readers then see the Chinese. Released versions need both languages
// (tests/release-notes.test.ts).
import type { Locale } from './i18n';

/** One change: Chinese and English, or (pending only) Chinese alone. */
export type ReleaseItem = string | readonly [zh: string, en: string];

export interface ReleaseNote {
  version: string;
  features: ReleaseItem[];
  fixes: ReleaseItem[];
}

/** The item in `locale`, falling back to Chinese where there is no English yet. */
export function releaseItemText(item: ReleaseItem, locale: Locale): string {
  return typeof item === 'string' ? item : locale === 'en' && item[1] ? item[1] : item[0];
}

const order = (version: string) => version.split('.').map(Number);
/** True when version a is later than version b (both "major.minor.patch"). */
export function isLaterVersion(a: string, b: string): boolean {
  const [x, y] = [order(a), order(b)];
  for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] > y[i];
  return false;
}

